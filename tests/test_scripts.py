def user(text, ts, cwd, meta=False):
    o = {"type": "user", "isSidechain": False, "message": {"role": "user", "content": text}, "timestamp": ts, "cwd": cwd,
         "entrypoint": "cli", "sessionId": "x"}
    if meta:
        o["isMeta"] = True
    return o


def asst(text, ts, tool=None):
    content = [{"type": "text", "text": text}]
    if tool:
        content.append({"type": "tool_use", "id": tool, "name": "Bash", "input": {"command": "npm test"}})
    return {"type": "assistant", "isSidechain": False, "message": {"role": "assistant", "content": content}, "timestamp": ts}


def tool_result(tid, text, ts, error=True):
    return {"type": "user", "isSidechain": False, "timestamp": ts,
            "message": {"role": "user", "content": [{"type": "tool_result", "tool_use_id": tid, "content": text, "is_error": error}]}}


def write_session(root, folder, sid, lines):
    d = os.path.join(root, folder)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, sid + ".jsonl"), "w", encoding="utf-8") as fh:
        for o in lines:
            fh.write(json.dumps(o) + "\n")


