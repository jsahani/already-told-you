            user("deploy a preview of the shop site to vercel and send me the preview link", day + "T09:01:00Z", cwd),
            asst("Done, deployed.", day + "T09:05:00Z", tool="t%d" % i),
            tool_result("t%d" % i, "<tool_use_error>Error: Exit code 1 npm ERR! missing script: test</tool_use_error>", day + "T09:05:05Z"),
