def parse_ts(s):
    try:
        return dt.datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()
    except Exception:
        return None


def project_name(cwd, folder):
    if cwd:
        parts = [p for p in cwd.rstrip("/").split("/") if p]
        if parts:
            return parts[-1] if len(parts) < 2 or parts[-1] not in ("src", "app", "web") else "/".join(parts[-2:])
    return folder.strip("-").split("-")[-1] or folder


def parse_session(path, folder):
    s = {
        "file": path, "folder": folder, "session": os.path.basename(path)[:-6], "cwd": None, "entry": None,
        "times": [], "msgs": [], "commands": collections.Counter(), "interrupts": 0, "errors": [], "rejections": 0,
        "assistant_turns": 0,
    }
    tool_names = {}
    last_assistant_text = ""
    assistant_since_user = False
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            is_user = has(line, "type", '"user"')
            is_asst = (not is_user) and has(line, "type", '"assistant"')
            if not (is_user or is_asst):
                if s["cwd"] is None and '"cwd":' in line:
                    m = RE_CWD.search(line)
                    if m:
                        s["cwd"] = m.group(1)
                continue
            if has(line, "isSidechain", "true"):
                continue
            m = RE_TS.search(line)
            ts = parse_ts(m.group(1)) if m else None
            if ts:
                s["times"].append(ts)
            if s["cwd"] is None:
                m = RE_CWD.search(line)
                if m:
                    s["cwd"] = m.group(1)
            if s["entry"] is None:
                m = RE_ENTRY.search(line)
                if m:
                    s["entry"] = m.group(1)
            if is_user and '"tool_result"' in line:
                # Large tool output lines: only parse when they carry an error or a rejection.
                if not has(line, "is_error", "true"):
                    continue
                try:
                    o = json.loads(line)
                except Exception:
                    continue
                for b in (o.get("message") or {}).get("content") or []:
                    if not isinstance(b, dict) or b.get("type") != "tool_result" or not b.get("is_error"):
                        continue
                    c = b.get("content")
                    if isinstance(c, list):
                        c = " ".join(x.get("text", "") for x in c if isinstance(x, dict))
                    c = str(c or "")
                    if "doesn't want to proceed" in c or "user rejected" in c.lower() or "was rejected" in c:
                        s["rejections"] += 1
                        continue
                    c = re.sub(r"</?tool_use_error>", "", c).strip()
                    s["errors"].append({"tool": tool_names.get(b.get("tool_use_id"), "tool"), "text": short(redact(c), 220), "ts": ts})
                continue
            try:
                o = json.loads(line)
            except Exception:
                continue
            if o.get("type") == "assistant":
                msg = o.get("message") or {}
                for b in msg.get("content") or []:
                    if not isinstance(b, dict):
                        continue
                    if b.get("type") == "tool_use":
                        tool_names[b.get("id")] = b.get("name", "tool")
                    elif b.get("type") == "text" and b.get("text", "").strip():
                        last_assistant_text = b["text"]
                if not assistant_since_user:
                    s["assistant_turns"] += 1
                assistant_since_user = True
                continue
            if o.get("type") != "user" or o.get("isMeta"):
                continue
            c = (o.get("message") or {}).get("content")
            if isinstance(c, list):
                if any(isinstance(b, dict) and b.get("type") == "tool_result" for b in c):
                    continue
                c = "\n".join(b.get("text", "") for b in c if isinstance(b, dict) and b.get("type") == "text")
            if not isinstance(c, str):
                continue
            kind, text, cmd = clean_user_text(c)
            if kind == "interrupt":
                s["interrupts"] += 1
                continue
            if kind == "skip":
                continue
            if kind == "command":
                s["commands"][cmd] += 1
                s["msgs"].append({"ts": ts, "text": (cmd + " " + text).strip(), "kind": "command", "after_assistant": assistant_since_user, "prev": ""})
            else:
                s["msgs"].append({"ts": ts, "text": text, "kind": "human", "after_assistant": assistant_since_user,
                                  "prev": short(last_assistant_text, 300) if assistant_since_user else ""})
            assistant_since_user = False
    s["times"].sort()
    s["start"] = s["times"][0] if s["times"] else None
    s["end"] = s["times"][-1] if s["times"] else None
    s["turns"] = len(s["msgs"])
    s["project"] = project_name(s["cwd"], folder)
    # active time: gaps between events, idle capped at 5 minutes
    cum = [0.0]
    for a, b in zip(s["times"], s["times"][1:]):
        cum.append(cum[-1] + min(max(b - a, 0), 300))
    s["cum"] = cum
    s["active_min"] = cum[-1] / 60.0
    first = next((m for m in s["msgs"] if m["kind"] == "human"), None)
    s["delegated"] = bool(first and is_agent_brief(first["text"]))
    return s


RE_BRIEF = re.compile(r"^(you are|you're|your (job|task|brief|role)|build |work only|read (the|this)|role:|task:|context:|#+ )", re.I)


def is_agent_brief(text):
    """A long, structured first message that reads like a brief written by another agent (or a pasted spec)."""
    if len(text) < 600:
        return False
    if RE_BRIEF.search(text.lstrip()):
        return True
    markers = sum(1 for m in ("report back", "do not ", "rules:", "deliverable", "acceptance", "\n- ", "\n1. ", "##") if m in text.lower())
    return markers >= 4


def active_between(s, t0, t1):
    if t0 is None or t1 is None or not s["times"]:
        return 0.0
    i = bisect.bisect_left(s["times"], t0)
    j = bisect.bisect_left(s["times"], t1)
    i = min(i, len(s["cum"]) - 1)
    j = min(max(j, i), len(s["cum"]) - 1)
    return (s["cum"][j] - s["cum"][i]) / 60.0


def day(ts):
    return dt.datetime.fromtimestamp(ts).strftime("%Y-%m-%d") if ts else "?"


