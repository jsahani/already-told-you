RE_URL = re.compile(r"https?://\S+")
RE_PATH = re.compile(r"(?:~|/)[\w.\-/@]+")
RE_WORD = re.compile(r"[a-z][a-z0-9'+\-]{2,}")


def tokens(text, limit=80):
    t = RE_URL.sub(" ", text.lower())
    t = RE_PATH.sub(" ", t)
    out = []
    seen = set()
    for w in RE_WORD.findall(t):
        w = w.strip("'-")
        if len(w) < 3 or w in STOP or w in seen or len(w) > 24 or sum(ch.isdigit() for ch in w) >= 3:
            continue
        seen.add(w)
        out.append(w)
        if len(out) >= limit:
            break
    return out


def cluster(items, threshold, key_tokens=10, merge_threshold=None):
    """Greedy clustering of short texts. items: list of dicts with 'tok' (list of tokens).

    Similarity is a rarity-weighted Jaccard (each token weighs log(N/df)), so generic words such as "open" or
    "check" count far less than distinctive ones such as "playwright". Each item is compared with the *core* of a
    cluster (tokens present in at least 40% of its members). Candidates come from an inverted index on rare
    tokens, so the work stays close to linear. A second pass merges clusters whose cores are similar.
    Returns a list of clusters (lists of item indexes)."""
    n = max(1, len(items))
    df = collections.Counter()
    for it in items:
        df.update(set(it["tok"]))
    idf = {w: max(0.05, math.log(n / float(c))) for w, c in df.items()}

    def wj(a, b):
        inter = sum(idf.get(w, 0) for w in a & b)
        if not inter:
            return 0.0
        return inter / (sum(idf.get(w, 0) for w in a | b) or 1.0)

    index = collections.defaultdict(set)
    clusters = []  # {"count": Counter, "n": int, "core": set, "members": []}

    def core_of(c):
        cut = max(1, int(0.4 * c["n"] + 0.999))
        core = {w for w, k in c["count"].items() if k >= cut}
        return core or set(w for w, _ in c["count"].most_common(6))

    for i, it in enumerate(items):
        tset = set(it["tok"])
        if not tset:
            continue
        rare = sorted(tset, key=lambda w: (df[w], w))[:key_tokens]
        cand = set()
        for w in rare:
            cand |= index.get(w, set())
        best, best_sim = None, 0.0
        for c in cand:
            sim = wj(tset, clusters[c]["core"])
            if sim > best_sim:
                best, best_sim = c, sim
        if best is not None and best_sim >= threshold:
            c = clusters[best]
            c["members"].append(i)
            c["count"].update(tset)
            c["n"] += 1
            c["core"] = core_of(c)
            for w in rare[:4]:
                index[w].add(best)
        else:
            cid = len(clusters)
            clusters.append({"count": collections.Counter(tset), "n": 1, "core": set(tset), "members": [i]})
            for w in rare:
                index[w].add(cid)

    # merge pass: union clusters (with 2+ members) whose cores are alike
    mt = merge_threshold if merge_threshold is not None else threshold + 0.05
    big = [k for k, c in enumerate(clusters) if c["n"] >= 2]
    parent = {k: k for k in range(len(clusters))}

    def find(k):
        while parent[k] != k:
            parent[k] = parent[parent[k]]
            k = parent[k]
        return k

    cidx = collections.defaultdict(list)
    for k in big:
        for w in sorted(clusters[k]["core"], key=lambda w: (df[w], w))[:6]:
            cidx[w].append(k)
    for k in big:
        seen = set()
        for w in sorted(clusters[k]["core"], key=lambda w: (df[w], w))[:6]:
            for j in cidx[w]:
                if j <= k or j in seen:
                    continue
                seen.add(j)
                if wj(clusters[k]["core"], clusters[j]["core"]) >= mt:
                    parent[find(j)] = find(k)
    groups = collections.defaultdict(list)
    for k, c in enumerate(clusters):
        groups[find(k)].extend(c["members"])
    return [sorted(m) for m in groups.values()]


