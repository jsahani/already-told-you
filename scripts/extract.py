RE_SYSREMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
RE_PASTED_IMG = re.compile(r"\[The pasted image\(s\)[^\]]*\]", re.S)
RE_APP_NOTE = re.compile(r"\[(?:Granular|Image|Pasted text|Image #\d+)[^\]]*\]", re.S)
RE_PASTED = re.compile(r"<pasted_content[^>]*>(.*?)</pasted_content>", re.S)
RE_COMMAND = re.compile(r"<command-name>\s*(/?[^<\s]+)\s*</command-name>")
RE_COMMAND_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S)
RE_BASH_INPUT = re.compile(r"<bash-input>(.*?)</bash-input>", re.S)
RE_ANY_TAG_BLOCK = re.compile(r"<(local-command-stdout|local-command-stderr|bash-stdout|bash-stderr|command-message|command-args|command-name)>.*?</\1>", re.S)
RE_TS = re.compile(r'"timestamp":\s?"([^"]+)"')
RE_CWD = re.compile(r'"cwd":\s?"((?:[^"\\]|\\.)*)"')
RE_ENTRY = re.compile(r'"entrypoint":\s?"([^"]+)"')


def has(line, key, value):
    """Fast substring test for "key":value in a JSON line, with or without a space after the colon."""
    return ('"%s":%s' % (key, value)) in line or ('"%s": %s' % (key, value)) in line

RE_SKILL_BLOCK = re.compile(r"<skill\b[^>]*>.*?(</skill>|$)", re.S)

# Messages written by Claude Code or by an app driving it, not typed by the user.
SKIP_PREFIXES = (
    "This session is being continued from a previous conversation",
    "Caveat: The messages below were generated by the user while running local commands",
    "Base directory for this skill:",
    "Worker report",
    "You were woken automatically",
    "The brief below is your memory of this conversation",
)
# App notes that ride along inside a real message: removed, the rest of the message is kept.
RE_INLINE_NOTES = re.compile(
    r"\((?:I interrupted your in-progress turn|Granular note:)[^)]*\)?"
    r"|\[(?:Granular|Image|Pasted text|Image #\d+)[^\]]*\]", re.S)

# Secrets and personal details never go into the digest (the report may be screen-recorded).
REDACTIONS = [
    (re.compile(r"\b(sk|pk|rk)[-_][A-Za-z0-9_\-]{16,}"), "[key]"),
    (re.compile(r"\b(ghp|gho|ghs|github_pat|xox[abp]|glpat)[-_A-Za-z0-9]{16,}"), "[token]"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "[key]"),
    (re.compile(r"\beyJ[A-Za-z0-9_\-]{20,}\.[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{10,}"), "[jwt]"),
    (re.compile(r"\b[A-Fa-f0-9]{32,}\b"), "[hex]"),
    (re.compile(r"(?i)\b(password|passwd|secret|token|api[_ -]?key)\s*[:=]\s*\S+"), r"\1: [hidden]"),
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"), "[email]"),
]


def redact(s):
    for rx, rep in REDACTIONS:
        s = rx.sub(rep, s)
    return s


def short(s, n):
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def clean_user_text(text):
    """Return (kind, cleaned_text, command). kind in: human, command, skip, interrupt."""
    if not text:
        return "skip", "", None
    t = text.strip()
    if "[Request interrupted by user" in t and len(t) < 120:
        return "interrupt", "", None
    for p in SKIP_PREFIXES:
        if t.startswith(p):
            return "skip", "", None
    m = RE_COMMAND.search(t)
    if m:
        cmd = m.group(1)
        if not cmd.startswith("/"):
            cmd = "/" + cmd
        am = RE_COMMAND_ARGS.search(t)
        args = (am.group(1).strip() if am else "")
        return "command", short(redact(args), 200), cmd
    m = RE_BASH_INPUT.search(t)
    if m:
        return "command", short(redact(m.group(1)), 120), "!bash"
    if t.startswith("<local-command") or t.startswith("<bash-std") or t.startswith("<command-message"):
        return "skip", "", None
    t = RE_SYSREMINDER.sub("", t)
    t = RE_SKILL_BLOCK.sub("", t)
    t = RE_PASTED_IMG.sub("", t)
    t = RE_INLINE_NOTES.sub("", t)
    t = RE_APP_NOTE.sub("", t)
    for p in SKIP_PREFIXES:
        if t.startswith(p):
            return "skip", "", None
    t = RE_PASTED.sub(lambda mm: " [pasted: " + short(mm.group(1), 120) + "] ", t)
    t = RE_ANY_TAG_BLOCK.sub("", t)
    t = t.strip()
    if not t:
        return "skip", "", None
    return "human", t, None


