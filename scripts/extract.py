def find_files(root, project_filter):
    out = []
    for folder in sorted(os.listdir(root)):
        p = os.path.join(root, folder)
        if not os.path.isdir(p):
            continue
        if project_filter:
            slug = re.sub(r"[^A-Za-z0-9]", "-", project_filter.rstrip("/"))
            if folder != slug and not folder.startswith(slug + "-"):
                continue
        for f in os.listdir(p):
            if f.endswith(".jsonl") and ".orphaned-" not in f:
                out.append((folder, os.path.join(p, f)))
    return out


def config_dir():
    """Claude Code's config folder: $CLAUDE_CONFIG_DIR if set, else ~/.claude."""
    return os.path.expanduser(os.environ.get("CLAUDE_CONFIG_DIR") or "~/.claude")


def read_cleanup_days(home=None):
    path = os.path.join(config_dir(), "settings.json")
    try:
        with open(path, encoding="utf-8") as fh:
            v = json.load(fh).get("cleanupPeriodDays")
        return v if isinstance(v, (int, float)) else None
    except Exception:
        return None


def main(argv=None):
    ap = argparse.ArgumentParser(description="Already Told You: digest your Claude Code history (read-only, local).")
    ap.add_argument("--report-root", default=None, help="writes into <root>/<YYYY-MM-DD>/data (e.g. ~/already-told-you)")
    ap.add_argument("--out", default=None, help="exact output folder (instead of --report-root)")
    ap.add_argument("--projects-dir", default=None, help="default: $CLAUDE_CONFIG_DIR/projects or ~/.claude/projects")
    ap.add_argument("--project", default=None, help="only sessions started in this folder (path)")
    ap.add_argument("--min-turns", type=int, default=3)
    ap.add_argument("--max-chars", type=int, default=120000)
    ap.add_argument("--compare", default="auto", help="previous findings.json to re-check; 'auto' = newest earlier report under --report-root; 'none' to skip")
    args = ap.parse_args(argv)

    t_start = time.time()
    home = os.path.expanduser("~")
    if not args.projects_dir:
        args.projects_dir = os.path.join(config_dir(), "projects")
    root = os.path.expanduser(args.projects_dir)
    today = dt.date.today().isoformat()
    if args.out:
        out = os.path.expanduser(args.out)
    elif args.report_root:
        out = os.path.join(os.path.expanduser(args.report_root), today, "data")
    else:
        ap.error("give --report-root or --out")
    report_dir = os.path.dirname(out.rstrip("/"))
    if args.compare == "auto":
        args.compare = find_previous(os.path.dirname(report_dir), os.path.basename(report_dir))
    elif args.compare == "none":
        args.compare = None
    if not os.path.isdir(root):
        print("No Claude Code history found at %s" % root, file=sys.stderr)
        return 2
    os.makedirs(os.path.join(out, "chunks"), exist_ok=True)

    files = find_files(root, args.project)
    total_bytes = sum(os.path.getsize(p) for _, p in files)
    sessions, oldest, newest = [], None, None
    for folder, path in files:
        try:
            s = parse_session(path, folder)
        except Exception as e:  # never die on one odd file
            print("skip %s: %s" % (path, e), file=sys.stderr)
            continue
        if s["start"]:
            oldest = s["start"] if oldest is None else min(oldest, s["start"])
            newest = s["end"] if newest is None else max(newest, s["end"])
        sessions.append(s)
    analysed = [s for s in sessions if s["turns"] >= args.min_turns and s["start"]]
    analysed.sort(key=lambda s: s["start"])

    # ---- templates: a long message (150+ chars) that opens with the same 120 characters in 3+ sessions is an
    # app prompt, a saved template or a habitual paste. Reported on its own, kept out of the clustering below.
    # Short messages typed again and again stay in: they are exactly the habits worth counting.
    prefix_sessions = collections.defaultdict(set)
    for si, s in enumerate(analysed):
        for m in s["msgs"]:
            m["template"] = False
            if m["kind"] == "human" and len(m["text"]) >= 150:
                m["pfx"] = " ".join(m["text"].lower().split())[:120]
                prefix_sessions[m["pfx"]].add(si)
    templates = collections.OrderedDict()
    for si, s in enumerate(analysed):
        for m in s["msgs"]:
            if m.get("pfx") and len(prefix_sessions[m["pfx"]]) >= 3:
                m["template"] = True
                t = templates.setdefault(m["pfx"], {"text": short(redact(m["text"]), 220), "count": 0, "sessions": set(),
                                                     "projects": collections.Counter(), "first": day(m["ts"]), "last": day(m["ts"])})
                t["count"] += 1
                t["sessions"].add(si)
                t["projects"][s["project"]] += 1
                t["last"] = max(t["last"], day(m["ts"]))
    for s in analysed:  # judge "delegated" on the first message that is not a template (e.g. a resume note)
        first = next((m for m in s["msgs"] if m["kind"] == "human" and not m["template"]), None)
        s["delegated"] = bool(first and is_agent_brief(first["text"]))
    templates = sorted(({"text": t["text"], "count": t["count"], "sessions": len(t["sessions"]), "first": t["first"], "last": t["last"],
                         "projects": dict(t["projects"].most_common(4))} for t in templates.values()), key=lambda x: -x["sessions"])

    # ---- requests (for repeated-task clustering) and segment minutes
    requests = []
    for si, s in enumerate(analysed):
        hum = [m for m in s["msgs"] if m["kind"] == "human" and not m["template"]]
        reqs = []
        for m in hum:
            tok = tokens(m["text"][:1500])
            if len(tok) >= 4:
                reqs.append((m, tok))
        for k, (m, tok) in enumerate(reqs):
            t_next = reqs[k + 1][0]["ts"] if k + 1 < len(reqs) else s["end"]
            mins = min(active_between(s, m["ts"], t_next), 180.0)
            requests.append({"si": si, "ts": m["ts"], "text": m["text"], "tok": tok[:40], "min": mins,
                             "brief": s["delegated"] and m is hum[0]})
    req_clusters = cluster(requests, 0.28)

    span_days = max(1.0, ((analysed[-1]["end"] - analysed[0]["start"]) / 86400.0) if analysed else 1.0)
    span_weeks = max(1.0, span_days / 7.0)

    def summarise(members, items):
        ses = sorted({items[i]["si"] for i in members})
        days = sorted({day(items[i]["ts"]) for i in members})
        projs = collections.Counter(analysed[items[i]["si"]]["project"] for i in members)
        mins = sum(items[i].get("min", 0) for i in members)
        ex, seen_s = [], set()
        for i in members:
            if items[i]["si"] in seen_s:
                continue
            seen_s.add(items[i]["si"])
            ex.append({"text": short(redact(items[i]["text"]), 220), "date": day(items[i]["ts"]),
                       "project": analysed[items[i]["si"]]["project"]})
        kw = collections.Counter()
        for i in members:
            kw.update(items[i]["tok"][:25])
        return {"count": len(members), "sessions": len(ses), "days": len(days), "first": days[0], "last": days[-1],
                "projects": dict(projs.most_common(5)), "minutes_total": round(mins, 1),
                "minutes_avg": round(mins / max(1, len(members)), 1),
                "per_week": round(len(days) / span_weeks, 2),
                "keywords": [w for w, _ in kw.most_common(8)], "examples": ex[:4]}

    tasks = []
    for members in req_clusters:
        sm = summarise(members, requests)
        if sm["sessions"] < 2:
            continue
        sm["score"] = round(sm["sessions"] * max(sm["minutes_avg"], 1.0), 1)
        tasks.append(sm)
    tasks.sort(key=lambda x: (-x["score"], -x["sessions"]))

    # ---- repeated context: sentences/lines re-explained across sessions
    sentences = []
    for si, s in enumerate(analysed):
        seen = set()
        for m in s["msgs"]:
            if m["kind"] != "human" or m["template"] or len(m["text"]) < 160:
                continue
            for part in re.split(r"(?<=[.!?])\s+|\n+", m["text"]):
                part = part.strip(" -*#>\t")
                tok = tokens(part, 60)
                if 5 <= len(tok) <= 45 and len(part) <= 600:
                    key = " ".join(sorted(tok))
                    if key in seen:
                        continue
                    seen.add(key)
                    sentences.append({"si": si, "ts": m["ts"], "text": part, "tok": tok})
    ctx = []
    for members in cluster(sentences, 0.55):
        sm = summarise(members, sentences)
        if sm["sessions"] < 3:
            continue
        sm["suggested_file"] = "~/.claude/CLAUDE.md" if len(sm["projects"]) >= 2 else "project CLAUDE.md (%s)" % next(iter(sm["projects"]))
        ctx.append(sm)
    ctx.sort(key=lambda x: (-x["sessions"], -x["count"]))

    # ---- corrections, errors, interrupts
    corrections = []
    for s in analysed:
        for m in s["msgs"]:
            if m["kind"] != "human" or m["template"] or not m["after_assistant"] or len(m["text"]) > 2500:
                continue
            labels = correction_labels(m["text"])
            if labels:
                corrections.append({"date": day(m["ts"]), "project": s["project"], "labels": labels,
                                    "text": short(redact(m["text"]), 260), "claude_before": short(redact(m["prev"]), 160),
                                    "delegated": s["delegated"]})
    label_counts = collections.Counter(l for c in corrections for l in c["labels"])

    err_groups = collections.defaultdict(list)
    for s in analysed:
        for e in s["errors"]:
            sig = re.sub(r"\d+", "N", e["text"].lower())
            sig = re.sub(r"(?:~|/)[\w.\-/@]+", "PATH", sig)
            sig = e["tool"] + ": " + " ".join(sig.split()[:9])
            err_groups[sig].append((s, e))
    errors = []
    for sig, lst in err_groups.items():
        ses = {id(x[0]) for x in lst}
        errors.append({"signature": sig, "tool": lst[0][1]["tool"], "count": len(lst), "sessions": len(ses),
                       "example": lst[0][1]["text"], "projects": dict(collections.Counter(x[0]["project"] for x in lst).most_common(3)),
                       "last": day(max((x[1]["ts"] or 0) for x in lst))})
    errors.sort(key=lambda x: (-x["sessions"], -x["count"]))

    commands = collections.Counter()
    for s in analysed:
        commands.update(s["commands"])

    by_project = collections.OrderedDict()
    for s in analysed:
        p = by_project.setdefault(s["project"], {"path": s["cwd"], "sessions": 0, "turns": 0, "minutes": 0.0, "first": day(s["start"]), "last": day(s["end"]),
                                                  "corrections": 0, "interrupts": 0, "errors": 0, "rejections": 0, "delegated": 0})
        p["sessions"] += 1
        p["turns"] += s["turns"]
        p["minutes"] += s["active_min"]
        p["last"] = max(p["last"], day(s["end"]))
        p["first"] = min(p["first"], day(s["start"]))
        p["interrupts"] += s["interrupts"]
        p["errors"] += len(s["errors"])
        p["rejections"] += s["rejections"]
        p["delegated"] += int(s["delegated"])
    for c in corrections:
        by_project[c["project"]]["corrections"] += 1

    cleanup = read_cleanup_days(home)
    stats = {
        "version": VERSION,
        "generated": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "scope": args.project or "all projects",
        "projects_dir": args.projects_dir,
        "bytes_read": total_bytes,
        "sessions_total": len(sessions),
        "sessions_analysed": len(analysed),
        "sessions_skipped_short": len([s for s in sessions if s["turns"] < args.min_turns]),
        "projects": len(by_project),
        "oldest_session": day(oldest), "newest_session": day(newest),
        "analysed_from": day(analysed[0]["start"]) if analysed else None,
        "analysed_to": day(analysed[-1]["end"]) if analysed else None,
        "span_days": round(span_days, 1),
        "your_messages": sum(1 for s in analysed for m in s["msgs"] if m["kind"] == "human"),
        "active_hours": round(sum(s["active_min"] for s in analysed) / 60.0, 1),
        "delegated_sessions": sum(1 for s in analysed if s["delegated"]),
        "corrections": len(corrections),
        "correction_types": dict(label_counts.most_common()),
        "interrupts": sum(s["interrupts"] for s in analysed),
        "tool_errors": sum(len(s["errors"]) for s in analysed),
        "rejected_tool_calls": sum(s["rejections"] for s in analysed),
        "slash_commands": dict(commands.most_common(25)),
        "cleanupPeriodDays": cleanup,
        "history_warning": None,
        "top_repeated_tasks": tasks[:15],
        "top_repeated_context": ctx[:15],
        "top_tool_errors": errors[:15],
        "templates": templates[:15],
        "by_project": by_project,
    }
    if cleanup is None or cleanup < 365:
        stats["history_warning"] = ("cleanupPeriodDays is %s, so Claude Code deletes transcripts older than %s days. "
                                    "Run /already-told-you:keep-history to keep a year." % (
                                        "not set" if cleanup is None else cleanup, 30 if cleanup is None else cleanup))

    # ---- compare with a previous run
    compare = None
    if args.compare:
        compare = compare_findings(os.path.expanduser(args.compare), analysed, corrections, err_groups)

    # ---- per-project chunks (detail for subagents)
    chunk_files = write_chunks(out, analysed)

    digest = build_digest(stats, analysed, tasks, ctx, corrections, errors, compare, chunk_files, args.max_chars, templates)
    with open(os.path.join(out, "digest.md"), "w", encoding="utf-8") as fh:
        fh.write(digest)
    stats["digest_chars"] = len(digest)
    stats["seconds"] = round(time.time() - t_start, 1)
    stats["chunk_files"] = chunk_files
    with open(os.path.join(out, "stats.json"), "w", encoding="utf-8") as fh:
        json.dump(stats, fh, indent=1, ensure_ascii=False)
    if compare is not None:
        with open(os.path.join(out, "compare.json"), "w", encoding="utf-8") as fh:
            json.dump(compare, fh, indent=1, ensure_ascii=False)
    print(json.dumps({k: stats[k] for k in ("sessions_total", "sessions_analysed", "projects", "oldest_session", "newest_session",
                                             "corrections", "interrupts", "tool_errors", "cleanupPeriodDays", "history_warning",
                                             "digest_chars", "seconds")}, ensure_ascii=False))
    print("digest: %s" % os.path.join(out, "digest.md"))
    print("report folder: %s" % report_dir)
    print("previous report compared: %s" % (args.compare or "none"))
    return 0


# Reports written before the plugin was renamed (it was called self-improve) live here; they still count as
# "previous" for the since-last-time comparison.
LEGACY_REPORT_ROOT = "~/claude-improve"


def find_previous(base, current_name, extra_bases=(LEGACY_REPORT_ROOT,)):
    """Newest <base>/<YYYY-MM-DD>/findings.json dated before the current report folder, or None.

    Looks in `base` and in each of `extra_bases` (the pre-rename report folder); the newest date wins."""
    found = []
    for b in [base] + [os.path.expanduser(x) for x in extra_bases]:
        try:
            names = [n for n in os.listdir(b) if re.match(r"^\d{4}-\d{2}-\d{2}$", n) and n < current_name]
        except Exception:
            continue
        for n in names:
            p = os.path.join(b, n, "findings.json")
            if os.path.isfile(p):
                found.append((n, p))
    return max(found)[1] if found else None


def compare_findings(path, analysed, corrections, err_groups):
    try:
        with open(path, encoding="utf-8") as fh:
            prev = json.load(fh)
    except Exception as e:
        return {"error": "could not read %s: %s" % (path, e)}
    since = (prev.get("generated") or "")[:10]
    try:
        since_ts = dt.datetime.strptime(since, "%Y-%m-%d").timestamp()
    except Exception:
        return {"error": "previous findings have no 'generated' date"}
    before_s = [s for s in analysed if s["start"] < since_ts]
    after_s = [s for s in analysed if s["start"] >= since_ts]
    wb = max(1.0, (since_ts - (before_s[0]["start"] if before_s else since_ts)) / 604800.0)
    wa = max(1.0 / 7, ((after_s[-1]["end"] - since_ts) / 604800.0) if after_s else 1.0 / 7)
    rows = []
    for sec in ("A", "B", "C", "D"):
        for f in (prev.get("sections") or {}).get(sec, []):
            kws = [k.lower() for k in (f.get("keywords") or []) if k]
            if not kws:
                continue
            nb = na = 0
            for group, n_ref in ((before_s, "b"), (after_s, "a")):
                for s in group:
                    for m in s["msgs"]:
                        if m["kind"] == "human" and any(k in m["text"].lower() for k in kws):
                            if n_ref == "b":
                                nb += 1
                            else:
                                na += 1
            rb, ra = nb / wb, na / wa
            if not after_s:
                status = "no new sessions yet"
            elif na == 0:
                status = "fixed"
            elif ra < rb * 0.5:
                status = "better"
            else:
                status = "still happening"
            rows.append({"section": sec, "id": f.get("id"), "title": f.get("title"), "before": nb, "after": na,
                         "per_week_before": round(rb, 2), "per_week_after": round(ra, 2), "status": status})
    return {"previous": since, "sessions_since": len(after_s), "findings": rows}


def slug(s):
    return re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-")[:60] or "project"


def write_chunks(out, analysed, cap=60000):
    by = collections.OrderedDict()
    for s in analysed:
        by.setdefault(s["project"], []).append(s)
    files = []
    for proj, ss in by.items():
        part, buf = 1, []
        size = 0

        def flush():
            nonlocal part, buf, size
            if not buf:
                return
            name = "%s-%d.md" % (slug(proj), part)
            with open(os.path.join(out, "chunks", name), "w", encoding="utf-8") as fh:
                fh.write("# %s (part %d)\n\nYour own messages only, trimmed to 300 characters. `[C]` = looks like a correction.\n\n" % (proj, part))
                fh.write("".join(buf))
            files.append(name)
            part += 1
            buf, size = [], 0

        for s in ss:
            head = "\n## %s · %d turns · %.0f min%s\n" % (day(s["start"]), s["turns"], s["active_min"], " · delegated brief" if s["delegated"] else "")
            lines = [head]
            for m in s["msgs"]:
                mark = "[C] " if (m["kind"] == "human" and m["after_assistant"] and correction_labels(m["text"])) else ""
                lines.append("- %s%s\n" % (mark, short(redact(m["text"]), 300)))
            if s["interrupts"]:
                lines.append("- (interrupted Claude %d×)\n" % s["interrupts"])
            block = "".join(lines)
            if size + len(block) > cap:
                flush()
            buf.append(block)
            size += len(block)
        flush()
    return files


def build_digest(stats, analysed, tasks, ctx, corrections, errors, compare, chunk_files, max_chars, templates=()):
    S = []
    S.append("# Already Told You - digest\n\nGenerated %s by extract.py %s. Scope: %s.\n" % (stats["generated"], VERSION, stats["scope"]))
    S.append("Quotes are the user's own messages (secrets, emails and long hex strings redacted). Times are estimates: "
             "active minutes = time between events with idle gaps capped at 5 minutes. A *delegated* session started with a long "
             "brief pasted or written by another agent; its first message may not be the user's own typing.\n")
    S.append("\n## Numbers\n")
    for k in ("sessions_total", "sessions_analysed", "sessions_skipped_short", "projects", "oldest_session", "newest_session",
              "span_days", "your_messages", "active_hours", "delegated_sessions", "corrections", "interrupts", "tool_errors",
              "rejected_tool_calls", "cleanupPeriodDays"):
        S.append("- %s: %s\n" % (k, stats[k]))
    if stats["history_warning"]:
        S.append("- WARNING: %s\n" % stats["history_warning"])
    S.append("- correction types: %s\n" % ", ".join("%s %d" % kv for kv in stats["correction_types"].items()))
    S.append("- slash commands: %s\n" % (", ".join("%s %d" % kv for kv in stats["slash_commands"].items()) or "none"))
    S.append("- detail files (the user's own messages per project, for subagents; paths relative to this digest): %s\n" % ", ".join("chunks/" + f for f in chunk_files))

    if templates:
        S.append("\n## Templates and app prompts (same opening in 3+ sessions; kept out of the clusters below)\n\n"
                 "Usually sent by an app or a saved snippet, sometimes a habit of pasting the same text. A habitual paste is a "
                 "candidate for CLAUDE.md or a skill; an app prompt is not something the user types.\n")
        for t in templates[:15]:
            S.append("- %d× in %d sessions (%s → %s; %s): \"%s\"\n" % (t["count"], t["sessions"], t["first"], t["last"],
                                                                       ", ".join(t["projects"]), t["text"]))

    if compare:
        S.append("\n## Previous findings re-checked (since %s)\n" % compare.get("previous"))
        if compare.get("error"):
            S.append("- %s\n" % compare["error"])
        for r in compare.get("findings", []):
            S.append("- [%s] %s: before %d (%.2f/wk), after %d (%.2f/wk) → **%s**\n" % (
                r["section"], r["title"], r["before"], r["per_week_before"], r["after"], r["per_week_after"], r["status"]))

    S.append("\n## Projects\n\n| project | path | sessions | active h | first | last | corrections | interrupts | tool errors | rejected calls |\n|---|---|---|---|---|---|---|---|---|---|\n")
    for p, v in sorted(stats["by_project"].items(), key=lambda kv: -kv[1]["sessions"]):
        S.append("| %s | %s | %d | %.1f | %s | %s | %d | %d | %d | %d |\n" % (p, v.get("path") or "?", v["sessions"], v["minutes"] / 60, v["first"], v["last"],
                                                                          v["corrections"], v["interrupts"], v["errors"], v["rejections"]))

    def task_block(title, rows, n, show_file=False):
        out = ["\n## %s\n" % title]
        for i, t in enumerate(rows[:n], 1):
            out.append("\n### %d. %s\n" % (i, " · ".join(t["keywords"][:5])))
            out.append("- %d times in %d sessions on %d days (%s → %s), ~%.2f days/week; est. %.0f min total, %.1f min each; projects: %s%s\n" % (
                t["count"], t["sessions"], t["days"], t["first"], t["last"], t["per_week"], t["minutes_total"], t["minutes_avg"],
                ", ".join("%s (%d)" % kv for kv in t["projects"].items()),
                ("; suggested file: " + t["suggested_file"]) if show_file else ""))
            for e in t["examples"][:3]:
                out.append('  - "%s" (%s, %s)\n' % (e["text"], e["date"], e["project"]))
        return out

    tail = []
    tail += task_block("Repeated tasks (similar requests across sessions, ranked by sessions × minutes)", tasks, 40)
    tail += task_block("Repeated context (the same explanation given in 3+ sessions)", ctx, 30, show_file=True)

    tail.append("\n## Repeated tool errors (mistakes Claude repeats)\n")
    for e in errors[:25]:
        tail.append("- %d× in %d sessions (last %s) · %s · e.g. \"%s\" · %s\n" % (
            e["count"], e["sessions"], e["last"], e["tool"], e["example"][:160], ", ".join(e["projects"])))

    tail.append("\n## Corrections (user turn right after Claude's, pushing back) - newest first\n")
    for c in sorted(corrections, key=lambda c: c["date"], reverse=True)[:220]:
        tail.append("- %s · %s%s · [%s] \"%s\"%s\n" % (c["date"], c["project"], " · delegated" if c["delegated"] else "", ", ".join(c["labels"]),
                                                    c["text"], ("  ← Claude had said: \"%s\"" % c["claude_before"]) if c["claude_before"] else ""))

    tail.append("\n## Session index (date · project · turns · minutes · first request)\n")
    for s in analysed:
        first = next((m["text"] for m in s["msgs"] if m["kind"] == "human"), "")
        tail.append("- %s · %s · %d · %.0f · %s\"%s\"\n" % (day(s["start"]), s["project"], s["turns"], s["active_min"],
                                                         "delegated · " if s["delegated"] else "", short(redact(first), 150)))

    head = "".join(S)
    body = "".join(tail)
    if len(head) + len(body) > max_chars:
        budget = max_chars - len(head) - 400
        cut = body[:budget]
        cut = cut[: cut.rfind("\n")]
        dropped = body.count("\n- ", len(cut))
        body = cut + "\n\n> Trimmed to fit %d characters: %d more lines (the long tail of corrections and the session index) are left out. They are in chunks/.\n" % (max_chars, dropped)
    return head + body


if __name__ == "__main__":
    sys.exit(main())
