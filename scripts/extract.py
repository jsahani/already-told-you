#!/usr/bin/env python3
"""Already Told You - extractor.

Reads Claude Code session transcripts (~/.claude/projects/<project>/<session>.jsonl), streaming
line by line, and writes a compact digest the model can analyse:

  <out>/digest.md      one markdown file, capped (default 120k chars) so it fits a model's context
  <out>/stats.json     the numbers (sessions, dates, corrections, clusters ...)
  <out>/chunks/*.md    per-project detail (your own messages, trimmed) for deeper reads by subagents
  <out>/compare.json   only with --compare: how often earlier findings still happen

Read-only on the transcripts. Python 3 standard library only. No network.
"""
